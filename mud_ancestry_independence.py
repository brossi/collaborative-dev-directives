    # VISUALIZATION 3: Prediction Error Distribution
    # ==================================================================
    print("  [7.3] Prediction error distribution...")

    fig, axes = plt.subplots(1, 2, figsize=(14, 5))

    # Side-by-side histograms
    ax1 = axes[0]
    bins = np.linspace(0, max(pred_error_train.max(), pred_error_indep.max()) + 0.02, 15)
    ax1.hist(pred_error_train, bins=bins, alpha=0.6, color="#2c3e50",
             edgecolor="white", label=f"Training (N={len(pred_error_train)})")
    ax1.hist(pred_error_indep, bins=bins, alpha=0.6, color="#e74c3c",
             edgecolor="white", label=f"Independent (N={len(pred_error_indep)})")
    ax1.axvline(np.mean(pred_error_train), color="#2c3e50",
                linestyle="--", linewidth=2, alpha=0.7,
                label=f"Train mean={np.mean(pred_error_train):.3f}")
    ax1.axvline(np.mean(pred_error_indep), color="#e74c3c",
                linestyle="--", linewidth=2, alpha=0.7,
                label=f"Indep mean={np.mean(pred_error_indep):.3f}")
    ax1.set_xlabel("|Predicted - Actual| Noise Floor", fontsize=11)
    ax1.set_ylabel("Count", fontsize=11)
    ax1.set_title("Prediction Error Distribution\n(Histograms)", fontsize=12,
                  fontweight="bold")
    ax1.legend(fontsize=8, loc="upper right")
    ax1.text(0.98, 0.55, f"Levene's test\np = {p_levene:.4f}",
             transform=ax1.transAxes, fontsize=10, ha="right",
             bbox=dict(boxstyle="round", facecolor="lightyellow", alpha=0.8))

    # KDE overlay
    ax2 = axes[1]
    if len(pred_error_train) > 1 and np.std(pred_error_train) > 1e-10:
        kde_x = np.linspace(0, max(pred_error_train.max(),
                                   pred_error_indep.max()) + 0.05, 200)
        try:
            kde_train = scipy_stats.gaussian_kde(pred_error_train)
            ax2.plot(kde_x, kde_train(kde_x), color="#2c3e50", linewidth=2,
                     label="Training pairs")
            ax2.fill_between(kde_x, kde_train(kde_x), alpha=0.2, color="#2c3e50")
        except np.linalg.LinAlgError:
            ax2.hist(pred_error_train, bins=10, alpha=0.4, color="#2c3e50",
                     density=True, label="Training pairs")

    if len(pred_error_indep) > 1 and np.std(pred_error_indep) > 1e-10:
        kde_x = np.linspace(0, max(pred_error_train.max(),
                                   pred_error_indep.max()) + 0.05, 200)
        try:
            kde_indep = scipy_stats.gaussian_kde(pred_error_indep)
            ax2.plot(kde_x, kde_indep(kde_x), color="#e74c3c", linewidth=2,
                     label="Independent pairs")
            ax2.fill_between(kde_x, kde_indep(kde_x), alpha=0.2, color="#e74c3c")
        except np.linalg.LinAlgError:
            ax2.hist(pred_error_indep, bins=10, alpha=0.4, color="#e74c3c",
                     density=True, label="Independent pairs")

    ax2.set_xlabel("|Predicted - Actual| Noise Floor", fontsize=11)
    ax2.set_ylabel("Density", fontsize=11)
    ax2.set_title("Prediction Error Distribution\n(KDE overlay)", fontsize=12,
                  fontweight="bold")
    ax2.legend(fontsize=9, loc="upper right")
    ax2.text(0.98, 0.55, f"Levene's test\np = {p_levene:.4f}",
             transform=ax2.transAxes, fontsize=10, ha="right",
             bbox=dict(boxstyle="round", facecolor="lightyellow", alpha=0.8))

    fig.suptitle("Does the Exp4 Regression Generalize? Prediction Error Comparison",
                 fontsize=13, fontweight="bold")
