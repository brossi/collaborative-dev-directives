def _ensure_bidirectional(G):
    """Make all edges bidirectional."""
    for u, v in list(G.edges()):
        if not G.has_edge(v, u):
            G.add_edge(v, u)


def _add_node_positions(G):
    """Add pos attribute to all nodes."""
    for n in G.nodes():
        r, c = room_coords(n)
        G.nodes[n]["pos"] = (c, GRID_ROWS - 1 - r)


def _ensure_connected_cardinal(G, rng):
    """If G is disconnected (as undirected), add minimum cardinal edges to connect.

    Only adds edges between cardinal-adjacent rooms (Manhattan distance 1).
    """
    G_undir = G.to_undirected()
    components = list(nx.connected_components(G_undir))
    if len(components) <= 1:
        return

    # Build list of all possible cardinal edges between different components
    comp_map = {}
    for ci, comp in enumerate(components):
        for node in comp:
            comp_map[node] = ci

    # Use union-find approach: greedily add cardinal edges to merge components
    parent = list(range(len(components)))

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(x, y):
        px, py = find(x), find(y)
        if px != py:
            parent[px] = py
            return True
        return False

    # Collect all potential cardinal bridge edges
    bridge_candidates = []
    for r in range(GRID_ROWS):
        for c in range(GRID_COLS):
            n = room_id(r, c)
            for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                nr, nc = r + dr, c + dc
                if 0 <= nr < GRID_ROWS and 0 <= nc < GRID_COLS:
                    m = room_id(nr, nc)
                    if comp_map[n] != comp_map[m]:
                        bridge_candidates.append((n, m))

    rng.shuffle(bridge_candidates)
    for u, v in bridge_candidates:
        cu, cv = comp_map[u], comp_map[v]
        if union(cu, cv):
            G.add_edge(u, v)
            G.add_edge(v, u)


def build_variant_f():
    """Variant F: Probabilistic Cardinal Grid.

    For each ~360 cardinal adjacency, include with p=0.80 (seed 700).
    Connectivity repair with minimum cardinal edges. No non-cardinal shortcuts.
    """
    rng = random.Random(700)
    G = nx.DiGraph()
    for n in range(100):
        r, c = room_coords(n)
        G.add_node(n, pos=(c, GRID_ROWS - 1 - r))

    # Enumerate all cardinal adjacencies and include with probability 0.80
    for r in range(GRID_ROWS):
        for c in range(GRID_COLS):
            n = room_id(r, c)
            for dr, dc in [(-1, 0), (1, 0), (0, -1), (0, 1)]:
                nr, nc = r + dr, c + dc
                if 0 <= nr < GRID_ROWS and 0 <= nc < GRID_COLS:
                    m = room_id(nr, nc)
                    if rng.random() < 0.80:
                        G.add_edge(n, m)

    _ensure_bidirectional(G)
    _ensure_connected_cardinal(G, rng)
    assert G.number_of_nodes() == 100
    assert nx.is_strongly_connected(G), "Variant F not strongly connected"
    return G


def build_variant_g():
    """Variant G: Radius-2 Geometric Graph.

    Connect all pairs within Manhattan distance <= 2. Then randomly remove edges
    (seed 701) until avg out-degree ~4.0, preserving connectivity.
    """
    rng = random.Random(701)
    G = nx.DiGraph()
    for n in range(100):
        r, c = room_coords(n)
        G.add_node(n, pos=(c, GRID_ROWS - 1 - r))

    # Add all distance-<=2 edges
    for r1 in range(GRID_ROWS):
        for c1 in range(GRID_COLS):
            n1 = room_id(r1, c1)
            for r2 in range(GRID_ROWS):
                for c2 in range(GRID_COLS):
                    if r1 == r2 and c1 == c2:
                        continue
                    if abs(r1 - r2) + abs(c1 - c2) <= 2:
                        n2 = room_id(r2, c2)
                        G.add_edge(n1, n2)

    # Trim: randomly remove edges until avg out-degree ~4.0
    target_degree = 4.0
    target_edges = int(target_degree * 100)  # 400 directed edges

    # Collect undirected edge pairs for removal
    undirected_edges = set()
    for u, v in G.edges():
        undirected_edges.add((min(u, v), max(u, v)))
    edge_list = list(undirected_edges)
    rng.shuffle(edge_list)

    for u, v in edge_list:
        if G.number_of_edges() <= target_edges:
            break
        # Don't create degree-0 nodes or break connectivity
        if G.out_degree(u) > 2 and G.out_degree(v) > 2:
            G.remove_edge(u, v)
            G.remove_edge(v, u)
            if not nx.is_strongly_connected(G):
                G.add_edge(u, v)
                G.add_edge(v, u)

    assert G.number_of_nodes() == 100
    assert nx.is_strongly_connected(G), "Variant G not strongly connected"
    return G


def _wilsons_algorithm(nodes, rng):
    """Generate a uniform random spanning tree using Wilson's algorithm.

    Returns a list of (u, v) undirected edges forming the tree.
    """
    n = len(nodes)
    node_set = set(nodes)
    # Build adjacency: fully connected (any node can reach any other)
    in_tree = set()
    tree_edges = []

    # Start with a random root
    root = rng.choice(nodes)
    in_tree.add(root)

    remaining = list(node_set - in_tree)
    rng.shuffle(remaining)

    for start in remaining:
        if start in in_tree:
            continue

        # Random walk from start until hitting the tree
        path = [start]
        current = start
        visited_in_walk = {start: 0}

        while current not in in_tree:
            # Choose random neighbor (any other node — complete graph)
            next_node = rng.choice(nodes)
            while next_node == current:
                next_node = rng.choice(nodes)

            if next_node in visited_in_walk:
                # Loop erasure: remove the cycle
                loop_start = visited_in_walk[next_node]
                # Remove entries from visited_in_walk for erased nodes
                for erased in path[loop_start + 1:]:
                    del visited_in_walk[erased]
                path = path[:loop_start + 1]
                current = next_node
            else:
                path.append(next_node)
                visited_in_walk[next_node] = len(path) - 1
                current = next_node

        # Add path to tree
        for i in range(len(path) - 1):
            tree_edges.append((path[i], path[i + 1]))
            in_tree.add(path[i])
        # The last node in path is already in tree
        in_tree.add(path[-1])

    return tree_edges


def build_variant_h():
    """Variant H: Spanning Tree + Random Rewiring.

    Wilson's algorithm (seed 702) for uniform random spanning tree.
    Add 150 random edges (seed 703). Target ~250 total edges.
    """
    nodes = list(range(100))

    # Wilson's algorithm for spanning tree
    rng_tree = random.Random(702)
    tree_edges = _wilsons_algorithm(nodes, rng_tree)

    G = nx.DiGraph()
    for n in nodes:
        r, c = room_coords(n)
        G.add_node(n, pos=(c, GRID_ROWS - 1 - r))

    for u, v in tree_edges:
        G.add_edge(u, v)
        G.add_edge(v, u)

    # Add 150 random edges
    rng_rewire = random.Random(703)
    added = 0
    attempts = 0
    while added < 150 and attempts < 10000:
        u = rng_rewire.randint(0, 99)
        v = rng_rewire.randint(0, 99)
        if u != v and not G.has_edge(u, v):
            G.add_edge(u, v)
            G.add_edge(v, u)
            added += 1
        attempts += 1

    assert G.number_of_nodes() == 100
    assert nx.is_strongly_connected(G), "Variant H not strongly connected"
    return G


def build_variant_i():
    """Variant I: Watts-Strogatz Small World.

    Ring topology (row-major order), K=3 nearest neighbors on each side,
    rewire with beta=0.25 (seed 704).
    """
    rng = random.Random(704)
    n = 100
    k_each_side = 3  # 6 connections per node

    G = nx.DiGraph()
    for node in range(n):
        r, c = room_coords(node)
        G.add_node(node, pos=(c, GRID_ROWS - 1 - r))

    # Ring: connect each node to K=3 nearest neighbors on each side
    for i in range(n):
        for j in range(1, k_each_side + 1):
            neighbor = (i + j) % n
            G.add_edge(i, neighbor)
            G.add_edge(neighbor, i)

    # Rewire with probability beta=0.25
    beta = 0.25
    edges_to_rewire = list(G.edges())
    rng.shuffle(edges_to_rewire)

    for u, v in edges_to_rewire:
        if rng.random() < beta:
            if not G.has_edge(u, v):
                continue
            # Rewire: keep u, change v to random node
            candidates = [x for x in range(n) if x != u and not G.has_edge(u, x)]
            if candidates:
                new_v = rng.choice(candidates)
                G.remove_edge(u, v)
                if G.has_edge(v, u) and G.out_degree(v) > 1:
                    G.remove_edge(v, u)
                G.add_edge(u, new_v)
                G.add_edge(new_v, u)

    _ensure_bidirectional(G)

    # Ensure connectivity
    if not nx.is_strongly_connected(G):
        _ensure_connected_cardinal(G, rng)

    assert G.number_of_nodes() == 100
    assert nx.is_strongly_connected(G), "Variant I not strongly connected"
    return G


def build_variant_j():
    """Variant J: Degree-Matched Random Graph (Configuration Model).

    Take Open's exact degree sequence. Generate random graph with same
    degree sequence using configuration model (seed 705).
    Resolve multi-edges/self-loops via edge swaps. Ensure connectivity.
    """
    rng = random.Random(705)
    np_rng = np.random.RandomState(705)

    G_open = build_variant_a()
    degree_seq = sorted([G_open.out_degree(n) for n in range(100)], reverse=True)

    # Use networkx configuration model on undirected graph
    # (since we want bidirectional edges, work with undirected then convert)
    # Ensure even sum
    if sum(degree_seq) % 2 != 0:
        degree_seq[0] += 1

    # Generate using configuration model with repeated attempts
    for attempt in range(50):
        try:
            G_undir = nx.configuration_model(degree_seq, seed=705 + attempt)
            # Remove self-loops and parallel edges
            G_undir = nx.Graph(G_undir)
            G_undir.remove_edges_from(nx.selfloop_edges(G_undir))
            break
        except nx.NetworkXError:
            continue

    # Build directed graph
    G = nx.DiGraph()
    for n in range(100):
        r, c = room_coords(n)
        G.add_node(n, pos=(c, GRID_ROWS - 1 - r))

    for u, v in G_undir.edges():
        if u < 100 and v < 100:
            G.add_edge(u, v)
            G.add_edge(v, u)

    # Ensure connectivity via edge swaps
    if not nx.is_strongly_connected(G):
        G_test = G.to_undirected()
        components = list(nx.connected_components(G_test))
        while len(components) > 1:
            # Pick two components and bridge them
            c1 = list(components[0])
            c2 = list(components[1])
            n1 = rng.choice(c1)
            n2 = rng.choice(c2)

            # Add bridge edge
            G.add_edge(n1, n2)
            G.add_edge(n2, n1)

            # Try to remove a random edge from the larger component to preserve degree
            c_large = c1 if len(c1) > len(c2) else c2
            edges_in_large = [(u, v) for u, v in G.edges()
                              if u in set(c_large) and v in set(c_large)
                              and G.out_degree(u) > 2 and G.out_degree(v) > 2]
            if edges_in_large:
                eu, ev = rng.choice(edges_in_large)
                G.remove_edge(eu, ev)
                if G.has_edge(ev, eu):
                    G.remove_edge(ev, eu)
                if not nx.is_strongly_connected(G):
                    G.add_edge(eu, ev)
                    G.add_edge(ev, eu)

            G_test = G.to_undirected()
            components = list(nx.connected_components(G_test))

    assert G.number_of_nodes() == 100
    assert nx.is_strongly_connected(G), "Variant J not strongly connected"
    return G


