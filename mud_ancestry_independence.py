    # --- Test 3: R^2 comparison (already computed above) ---

    # --- Test 4: Ancestry interaction test ---
    # noise_floor = b1*jaccard + b2*ancestry + b3*jaccard*ancestry + intercept
    # ancestry = 1 if either variant derives from Open, 0 otherwise
    ancestry_exp4 = np.ones(len(exp4_jaccard))     # All derive from Open
